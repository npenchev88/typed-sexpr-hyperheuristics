(ns generate-springer-svgs
  "CLI entry point to generate all 5 Springer-compliant publication SVGs,
   the companion LaTeX figure environments (`docs/figures/springer/springer_figures.tex`),
   and the machine-readable manifest (`docs/figures/springer/figures-manifest.edn`).

   Usage:
     .\\clojure.cmd -M scripts/generate-springer-svgs.clj
     .\\clojure.cmd -M scripts/generate-springer-svgs.clj docs/evidence/g8-thirty-replications-results.edn"
  (:require [clojure.edn :as edn]
            [clojure.java.io :as io]
            [clojure.pprint :as pprint]
            [niki.optimizer.springer-figures :as sfig]))

(defn write-springer-latex!
  [out-path]
  (let [tex
        "% =============================================================================
% Springer Publication Figure Environments (LNCS `llncs.cls` / Journal `sn-jnl.cls`)
% Auto-generated by `scripts/generate-springer-svgs.clj`
% Tip: Use `\\usepackage{svg}` with `\\includesvg[width=\\textwidth]{...}` or convert
%      each SVG to PDF via `inkscape --export-type=pdf` and use `\\includegraphics`.
% =============================================================================

\\begin{figure}[t]
  \\centering
  \\includegraphics[width=\\textwidth]{figures/springer/fig1_architecture_and_dsl.pdf}
  \\caption{\\textbf{System architecture of the typed executable optimizer laboratory.}
  \\textbf{(a)} Binder-free, sort-stratified Domain-Specific Language (DSL) over six syntactic roles
  (\\texttt{:operation}, \\texttt{:predicate}, \\texttt{:score}, \\texttt{:count}, \\texttt{:initializer},
  and \\texttt{:operator}), guaranteeing 100\\% valid-by-construction execution under typed generation,
  subtree mutation, and homologous crossover.
  \\textbf{(b)} Unchanged shared core verified via locked SHA-256 hashes across domains (Hypothesis H5),
  enforcing a dual resource ledger: an outer 256-assessment-slot allowance (where duplicates and
  fallbacks consume slots) and an inner 256-proposal / 4,096-step runtime cap (where cache hits still
  charge one proposal unit).
  \\textbf{(c--d)} Domain adapters for exact-$K$ cardinality-constrained portfolio selection
  ($N=50, K=5, T=365$) and 30-job single-machine permutation scheduling.}
  \\label{fig:architecture}
\\end{figure}

\\begin{figure}[t]
  \\centering
  \\includegraphics[width=\\textwidth]{figures/springer/fig2_pareto_fronts_2panel.pdf}
  \\caption{\\textbf{Bi-objective Pareto fronts, dominated decision clouds, and hypervolume geometry.}
  \\textbf{(a)} Exact-$K$ portfolio selection ($N=15, K=5$, all $\\binom{15}{5}=3{,}003$ subsets) minimizing
  negative mean daily return ($-\\mu_p$) and daily return standard deviation ($\\sigma_p$).
  \\textbf{(b)} Single-machine scheduling (30 jobs, $B=256$ proposals) minimizing mean completion time
  and total tardiness alongside classical dispatching heuristics (SPT: blue diamond; EDD: purple square).
  In both panels, initial random solutions are marked by amber triangles, dominated solutions by grey dots,
  and nondominated Pareto-optimal solutions by emerald circles.
  Because both decision spaces ($\\binom{N}{K}$ subsets and $n!$ permutations) are finite combinatorial sets,
  the true Pareto set $P^\\star$ is a finite collection of discrete points rather than a continuous manifold.
  We therefore display two complementary geometric objects: (i) a \\emph{smooth Fritsch--Carlson monotone cubic
  Hermite curve} (solid dark-emerald line) illustrating the continuous shape-preserving trade-off trend without
  artificial overshoot, and (ii) the \\emph{exact 2-D Hypervolume attainment region} (light emerald shading bounded
  by a dashed orthogonal staircase), which reflects the axis-aligned dominance cones $\\bigcup_{p \\in A}[p, r]$
  integrated with respect to the reference point $r$.}
  \\label{fig:pareto-fronts}
\\end{figure}

\\begin{figure}[t]
  \\centering
  \\includegraphics[width=\\textwidth]{figures/springer/fig3_five_arms_and_prior_ablation.pdf}
  \\caption{\\textbf{Held-out test normalized hypervolume across all five outer search arms and generator priors.}
  Comparison of evolved executable optimizers (\\texttt{A1: GP-Mixed}, \\texttt{A2: GP-Mutation-Only}),
  random program sampling (\\texttt{A3: Random-DSL}), fixed-scaffold expression evolution
  (\\texttt{A4: Formula-Only}), and configured classical multi-objective baselines
  (\\texttt{A5: Configured-Conventional}, NSGA-II / PLS) on \\textbf{(a)} Portfolio Selection ($N=50, K=5, T=365$)
  and \\textbf{(b)} Single-Machine Scheduling (30 jobs).
  Grouped bars compare the naive uniform prior (\\texttt{:development-only-v1}, amber with triangle markers)
  against the capacity-preserving prior (\\texttt{:budget-aware-v2}, emerald with circle markers), which
  eliminates outer-slot starvation and achieves practically superior test hypervolume gains ($p < 0.0001$).}
  \\label{fig:five-arms-and-prior}
\\end{figure}

\\begin{figure}[t]
  \\centering
  \\includegraphics[width=\\textwidth]{figures/springer/fig4_anytime_budget_scaling.pdf}
  \\caption{\\textbf{Anytime performance scaling across inner solution proposal budgets $B \\in \\{16, 32, 64, 128, 256\\}$.}
  Frozen winning optimizers and configured baselines evaluated on held-out test instances at five logarithmic
  proposal budgets on \\textbf{(a)} Portfolio Selection and \\textbf{(b)} Single-Machine Scheduling.
  Distinct geometric marker shapes (circle, square, diamond, triangle, cross) and stroke dash styles ensure
  legibility in both color and grayscale print.}
  \\label{fig:budget-scaling}
\\end{figure}

\\begin{figure}[t]
  \\centering
  \\includegraphics[width=\\textwidth]{figures/springer/fig5_mechanism_ablations_3panel.pdf}
  \\caption{\\textbf{Secondary mechanism ablations verifying the sources of evolutionary and runtime performance.}
  \\textbf{(a)} Per-attempt syntactic/sort validation hit rate (\\%) for typed sort-directed variation
  (\\texttt{:budget-aware-v2}, emerald) versus untyped grammar-blind tree variation with post-hoc validation
  (\\texttt{:untyped-validated}, vermilion), where untyped generation and mutation suffer $>90\\%$ rejection rates.
  \\textbf{(b)} Surgical AST knockouts (\\texttt{K0}--\\texttt{K6}) on frozen winning portfolio optimizers:
  deleting the evolved search body (\\texttt{K1}) collapses hypervolume by $-0.491$, blinding the score expression
  (\\texttt{K3}) drops hypervolume by $-0.129$, and collapsing bi-objective trade-offs to a single objective
  (\\texttt{K6}) drops hypervolume by $-0.037$, whereas neutralizing the initializer (\\texttt{K2}) changes
  hypervolume by only $-0.001$.
  \\textbf{(c)} Inner candidate memoization cache-off (\\texttt{:cache? false}, grey) versus cache-on
  (\\texttt{:cache? true}, emerald): because cache hits still charge one proposal unit, held-out test
  hypervolume is bitwise identical ($|\\Delta\\text{HV}| = 0.0$) while physical objective evaluations are
  reduced by 14.5\\%--16.5\\%.}
  \\label{fig:mechanism-ablations}
\\end{figure}

\\begin{figure}[t]
  \\centering
  \\includegraphics[width=\\textwidth]{figures/springer/fig6_meta_evolution_and_ast_structure.pdf}
  \\caption{\\textbf{Outer meta-evolution trajectory and syntactic structure of the 30 final evolved programs.}
  \\textbf{(a)} Mean best-so-far training normalized hypervolume across the 8 outer assessment batches
  ($8 \\times 32 = 256$ slots, $N=30$ independent seeds) for \\texttt{A1: GP-Mixed}, \\texttt{A2: GP-Mutation-Only},
  and \\texttt{A4: Formula-Only}, demonstrating substantial multi-generation improvement over batch 0
  ($+0.047$ to $+0.049$ training hypervolume).
  \\textbf{(b)} Frequency tally of syntactic roles, operators, and features across the 30 final selected
  \\texttt{GP-Mixed} programs on Portfolio Selection (emerald, 30/30 syntactically unique) and Single-Machine
  Scheduling (purple, 30/30 syntactically unique), showing automatic domain-appropriate operator selection
  (\\texttt{:swap} and \\texttt{:restart} in Portfolio versus \\texttt{:insert}, \\texttt{:swap}, and \\texttt{:first}
  in Scheduling) alongside bi-objective (\\texttt{:objective-0} + \\texttt{:objective-1}) and non-stationary
  progress-adaptive (\\texttt{:progress}) scoring formulas.}
  \\label{fig:meta-evolution-and-ast}
\\end{figure}
"]
    (io/make-parents out-path)
    (spit out-path tex :encoding "UTF-8")
    (println "Wrote Springer LaTeX figure environments:" out-path)))

(defn -main [& args]
  (let [default-edn (if (.exists (io/file "docs/evidence/g8-thirty-replications-results.edn"))
                      "docs/evidence/g8-thirty-replications-results.edn"
                      "docs/evidence/two-replication-ablation-results.edn")
        primary-edn-path (or (first args) default-edn)
        _ (println "=== Generating Springer-Compliant Publication SVGs ===")
        _ (println "Primary arms & prior evidence:" primary-edn-path)
        two-rep-edn  (edn/read-string (slurp primary-edn-path))
        scaling-edn  (edn/read-string (slurp "docs/evidence/budget-scaling-ablation-results.edn"))
        knockout-edn (edn/read-string (slurp "docs/evidence/ast-knockout-ablation-results.edn"))
        cache-edn    (edn/read-string (slurp "docs/evidence/cache-ablation-results.edn"))
        typed-edn    (edn/read-string (slurp "docs/evidence/typed-vs-untyped-ablation-results.edn"))
        out-dir      "docs/figures/springer"
        fig1-path    (str out-dir "/fig1_architecture_and_dsl.svg")
        fig2-path    (str out-dir "/fig2_pareto_fronts_2panel.svg")
        fig3-path    (str out-dir "/fig3_five_arms_and_prior_ablation.svg")
        fig4-path    (str out-dir "/fig4_anytime_budget_scaling.svg")
        fig5-path    (str out-dir "/fig5_mechanism_ablations_3panel.svg")
        fig6-path    (str out-dir "/fig6_meta_evolution_and_ast_structure.svg")
        tex-path     (str out-dir "/springer_figures.tex")
        manifest-path (str out-dir "/figures-manifest.edn")]
    (sfig/generate-fig1-architecture! fig1-path)
    (sfig/generate-fig2-pareto-fronts! fig2-path)
    (sfig/generate-fig3-arms-and-prior! two-rep-edn fig3-path)
    (sfig/generate-fig4-budget-scaling! scaling-edn fig4-path)
    (sfig/generate-fig5-mechanism-ablations! typed-edn knockout-edn cache-edn fig5-path)
    (sfig/generate-fig6-evolution-and-ast-tally! two-rep-edn fig6-path)
    (write-springer-latex! tex-path)
    (let [manifest
          {:generated-at (str (java.time.Instant/now))
           :publisher-target "Springer (LNCS llncs.cls 122mm / Springer Nature sn-jnl.cls 174mm)"
           :typography {:font-family "Helvetica, Arial, sans-serif"
                        :code-font-family "Consolas, monospace"
                        :panel-labels "Bold lowercase (a), (b), (c), (d)"
                        :print-caption-mode true}
           :accessibility {:palette "Okabe-Ito colorblind-safe"
                           :grayscale-encodings "Distinct geometric markers (:circle, :triangle, :square, :diamond, :cross) + stroke-dasharray"}
           :source-evidence {:primary-arms primary-edn-path
                             :budget-scaling "docs/evidence/budget-scaling-ablation-results.edn"
                             :ast-knockout "docs/evidence/ast-knockout-ablation-results.edn"
                             :cache-ablation "docs/evidence/cache-ablation-results.edn"
                             :typed-vs-untyped "docs/evidence/typed-vs-untyped-ablation-results.edn"}
           :figures [{:id :fig1 :file fig1-path :viewBox [0 0 760 300] :width-mm 174.0 :height-mm 68.7
                      :description "System Architecture, 6-Role Typed DSL, Dual Resource Ledger, and Domain Adapters"}
                     {:id :fig2 :file fig2-path :viewBox [0 0 760 345] :width-mm 174.0 :height-mm 79.0
                      :description "2-Panel Portfolio & Scheduling Pareto Fronts with Smooth Monotone Cubic Curve + Shaded HV Step Region"}
                     {:id :fig3 :file fig3-path :viewBox [0 0 760 330] :width-mm 174.0 :height-mm 75.5
                      :description "2-Panel Five Search Arms & Generator Prior Ablation (:development-only-v1 vs :budget-aware-v2, N=30 seeds)"}
                     {:id :fig4 :file fig4-path :viewBox [0 0 760 335] :width-mm 174.0 :height-mm 76.7
                      :description "2-Panel Anytime Proposal-Budget Scaling Trajectory B in {16, 32, 64, 128, 256}"}
                     {:id :fig5 :file fig5-path :viewBox [0 0 760 305] :width-mm 174.0 :height-mm 69.8
                      :description "3-Panel Secondary Mechanism Ablations: (a) Typed vs Untyped Hit Rate, (b) Surgical AST Knockouts, (c) Cache Eval Savings"}
                     {:id :fig6 :file fig6-path :viewBox [0 0 760 325] :width-mm 174.0 :height-mm 74.4
                      :description "2-Panel 30-Seed Meta-Evolution Batch Trajectory & Final AST Feature Tally"}]
           :latex-companion tex-path}]
      (spit manifest-path (with-out-str (pprint/pprint manifest)) :encoding "UTF-8")
      (println "Wrote Springer figures manifest:" manifest-path))))

(apply -main *command-line-args*)
